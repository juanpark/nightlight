"""The one-line installer (web/lib/installScript.ts): a device without a usable python3 gets Nightlight's own pinned
Python instead of a dead end; a device with one behaves as before; what's downloaded is checked without Python."""

import hashlib
import json
import os
import re
import shutil
import subprocess
import tarfile
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
TS = ROOT / "web" / "lib" / "installScript.ts"
HELPER = ROOT / "helper" / "nightlight_helper.py"

pytestmark = pytest.mark.skipif(not shutil.which("node"), reason="needs node (type stripping, Node >= 22.18)")


def _script(tmp_path, kind):
    """The script the web server would send, generated by the real TypeScript module."""
    site = tmp_path / "site"
    (site / "public").mkdir(parents=True, exist_ok=True)
    shutil.copy(HELPER, site / "public" / "nightlight_helper.py")
    js = (f"const m = await import({json.dumps(str(TS))});"
          f"const r = await m.{kind}(new Request('https://nightlight.example/install.sh'));"
          "process.stdout.write(r.body);")
    out = subprocess.run(["node", "--input-type=module", "-e", js], cwd=site, capture_output=True, text=True,
                         check=True, env={**os.environ, "API_URL": "https://api.example"})
    return out.stdout


def _functions(tmp_path, kind="installScript"):
    """The script with its last line (`main "$@"`) removed, so a test can call single functions."""
    body = _script(tmp_path, kind)
    assert body.rstrip().endswith('main "$@"')
    return body.rstrip()[: -len('main "$@"')]


def _bin(tmp_path, tools, extra=None):
    """A PATH with only the named system tools (so python3 can be made absent) plus fakes."""
    b = tmp_path / "bin"
    b.mkdir(exist_ok=True)
    for t in tools:
        src = shutil.which(t)
        if src and not (b / t).exists():
            (b / t).symlink_to(src)
    for name, text in (extra or {}).items():
        (b / name).write_text("#!/bin/sh\n" + text)
        (b / name).chmod(0o755)
    return str(b)


BASE = ["sh", "mkdir", "rm", "mv", "rmdir", "chmod", "cut", "sed", "tar", "gzip", "ls", "mktemp", "cat", "id",
        "readlink", "grep", "printf", "xcode-select", "getconf", "sha256sum", "shasum", "openssl", "perl"]


def _run(tmp_path, kind, tail, path, home):
    code = _functions(tmp_path, kind) + "\n" + tail + "\n"
    return subprocess.run(["/bin/sh", "-c", code], capture_output=True, text=True, timeout=60,
                          env={"PATH": path, "HOME": str(home)})


@pytest.mark.parametrize("kind", ["installScript", "uninstallScript"])
def test_scripts_parse_in_posix_shells(tmp_path, kind):
    body = _script(tmp_path, kind)
    for sh in ("sh", "dash", "bash"):
        if shutil.which(sh):
            r = subprocess.run([sh, "-n"], input=body, capture_output=True, text=True)
            assert r.returncode == 0, (sh, r.stderr)
    if shutil.which("shellcheck"):
        r = subprocess.run(["shellcheck", "-s", "sh", "-e", "SC2016,SC1003", "-"], input=body, capture_output=True,
                           text=True)
        assert r.returncode == 0, r.stdout
    # The helper's checksum no longer needs Python (it may not be here yet).
    assert "hashlib" not in body


def test_pins_match_the_mac_installer():
    """Same python-build-standalone release and the same darwin digests as scripts/build_mac_pkg.sh."""
    pkg = (ROOT / "scripts" / "build_mac_pkg.sh").read_text()
    ts = TS.read_text()
    tag = re.search(r"^PBS_TAG=(\S+)", pkg, re.M).group(1)
    py = re.search(r"^PBS_PY=(\S+)", pkg, re.M).group(1)
    assert f'PBS_TAG = "{tag}"' in ts and f'PBS_PY = "{py}"' in ts
    for arch, triple in (("arm64", "aarch64-apple-darwin"), ("x86_64", "x86_64-apple-darwin")):
        sha = re.search(rf"^PBS_SHA_{arch}=(\S+)", pkg, re.M).group(1)
        assert f'"{triple}": ["{sha}"' in ts
    for triple in ("x86_64-unknown-linux-gnu", "aarch64-unknown-linux-gnu", "armv7-unknown-linux-gnueabihf"):
        assert re.search(rf'"{triple}": \["[0-9a-f]{{64}}"', ts)


def test_a_usable_system_python_is_used_as_before(tmp_path):
    path = _bin(tmp_path, BASE + ["python3", "uname"])
    r = _run(tmp_path, "installScript", 'need_python; echo "PY=$PY"', path, tmp_path / "home")
    assert r.returncode == 0, r.stderr
    assert f"PY={tmp_path / 'bin' / 'python3'}" in r.stdout
    assert not (tmp_path / "home").exists() or not any((tmp_path / "home").rglob("python"))


def test_nightlights_own_python_is_preferred_once_it_exists(tmp_path):
    home = tmp_path / "home"
    app = home / ".local/share/nightlight" if os.uname().sysname != "Darwin" else home / "Library/Application Support/Nightlight"
    (app / "python/bin").mkdir(parents=True)
    (app / "python/bin/python3").symlink_to(shutil.which("python3"))
    path = _bin(tmp_path, BASE + ["uname"])  # no python3 on PATH
    r = _run(tmp_path, "installScript", 'need_python; echo "PY=$PY"', path, home)
    assert r.returncode == 0, r.stderr
    assert f"PY={app / 'python/bin/python3'}" in r.stdout


def _fake_tarball(tmp_path):
    """A stand-in for the python-build-standalone archive: python/bin/python3 that works."""
    src = tmp_path / "tb"
    (src / "python/bin").mkdir(parents=True)
    (src / "python/bin/python3").write_text(f'#!/bin/sh\nexec {shutil.which("python3")} "$@"\n')
    (src / "python/bin/python3").chmod(0o755)
    tgz = tmp_path / "py.tar.gz"
    with tarfile.open(tgz, "w:gz") as t:
        t.add(src / "python", arcname="python")
    return tgz


def _fake_curl(tmp_path, tgz):
    """curl that serves the fake archive for any URL and records what was asked for."""
    log = tmp_path / "curl.log"
    return {"curl": f'out=""; while [ $# -gt 0 ]; do case "$1" in -o) out="$2"; shift;; https:*) echo "$1" >> {log};; '
                    f'esac; shift; done; cp {tgz} "$out"\n'}, log


def test_no_python_fetches_the_pinned_build_and_refuses_a_wrong_checksum(tmp_path):
    tgz = _fake_tarball(tmp_path)
    fakes, log = _fake_curl(tmp_path, tgz)
    fakes["uname"] = 'case "$1" in -s) echo Linux;; -m) echo x86_64;; esac\n'
    path = _bin(tmp_path, BASE + ["cp"], fakes)
    home = tmp_path / "home"
    r = _run(tmp_path, "installScript", 'need_python; echo "PY=$PY"', path, home)
    assert r.returncode == 1
    assert "didn't match its checksum, so nothing was installed" in r.stderr
    url = log.read_text().strip()
    assert url == ("https://github.com/astral-sh/python-build-standalone/releases/download/20260929/"
                   "cpython-3.12.14%2B20260929-x86_64-unknown-linux-gnu-install_only.tar.gz")
    assert not (home / ".local/share/nightlight/python").exists()


def test_no_python_unpacks_a_matching_build_into_nightlights_folder(tmp_path):
    """With the digest replaced by the fake archive's own, the whole path runs: download, verify, unpack, use."""
    tgz = _fake_tarball(tmp_path)
    fakes, _ = _fake_curl(tmp_path, tgz)
    fakes["uname"] = 'case "$1" in -s) echo Linux;; -m) echo aarch64;; esac\n'
    fakes["getconf"] = "echo 64\n"
    path = _bin(tmp_path, ["cp"] + [t for t in BASE if t != "getconf"], fakes)
    home = tmp_path / "home"
    real = re.search(r'"aarch64-unknown-linux-gnu": \["([0-9a-f]{64})"', TS.read_text()).group(1)
    code = _functions(tmp_path).replace(real, hashlib.sha256(tgz.read_bytes()).hexdigest())
    code += 'need_python; echo "PY=$PY"; "$PY" -c "print(40 + 2)"\nremove_own_python; [ ! -e "$APP_DIR" ] && echo GONE\n'
    r = subprocess.run(["/bin/sh", "-c", code], capture_output=True, text=True, timeout=60,
                       env={"PATH": path, "HOME": str(home)})
    assert r.returncode == 0, r.stderr
    assert f"PY={home}/.local/share/nightlight/python/bin/python3" in r.stdout
    assert "about 52 MB" in r.stdout and "42" in r.stdout
    assert "Removed Nightlight's own Python." in r.stdout and "GONE" in r.stdout


@pytest.mark.parametrize("os_arch, says", [
    (("Linux", "riscv64"), "this processor (riscv64)"),
    (("Linux", "x86_64", "musl"), "apk add python3"),
    (("FreeBSD", "amd64"), "this system (FreeBSD amd64)"),
])
def test_unsupported_systems_get_a_plain_next_step(tmp_path, os_arch, says):
    fakes = {"uname": f'case "$1" in -s) echo {os_arch[0]};; -m) echo {os_arch[1]};; esac\n'}
    if len(os_arch) == 3:  # musl: the loader file Alpine has
        fakes["ls"] = 'case "$1" in /lib/ld-musl-*) exit 0;; esac; exit 2\n'
    path = _bin(tmp_path, [t for t in BASE if t != "ls"] + ([] if len(os_arch) == 3 else ["ls"]), fakes)
    r = _run(tmp_path, "installScript", "need_python", path, tmp_path / "home")
    assert r.returncode == 1
    assert says in r.stderr and "run the line again" in r.stderr


def test_mac_stub_python_without_developer_tools_is_not_used(tmp_path):
    """Apple's /usr/bin/python3 without the command line tools only offers to install them: never call it."""
    code = _functions(tmp_path)
    fakes = {"uname": 'case "$1" in -s) echo Darwin;; -m) echo arm64;; esac\n', "xcode-select": "exit 2\n"}
    path = _bin(tmp_path, [t for t in BASE if t != "xcode-select"], fakes)
    # Pretend python3 resolves to the stub path: command -v is a builtin, so override it for this one name.
    code += ('command() { if [ "$1" = -v ] && [ "$2" = python3 ]; then echo /usr/bin/python3; else builtin command "$@"; fi; }\n'
             'system_python_ok && echo USED || echo SKIPPED\n')
    r = subprocess.run([shutil.which("bash"), "-c", code], capture_output=True, text=True, env={"PATH": path, "HOME": str(tmp_path)})
    assert "SKIPPED" in r.stdout, r.stderr


def test_command_link_is_only_removed_when_it_is_ours(tmp_path):
    body = _script(tmp_path, "uninstallScript")
    assert "unlink_command" in body and "remove_own_python" in body
    assert body.index("helper uninstall") < body.index("remove_own_python\n  say")
    ins = _script(tmp_path, "installScript")
    assert ins.index("helper install") < ins.index("  link_command\n")


def test_staging_folder_is_always_private_and_never_inherited(tmp_path):
    """An inherited TMP or NL_TMP must not choose where downloads land (a pre-planted link could be swapped in)."""
    evil = tmp_path / "shared"
    evil.mkdir()
    code = _functions(tmp_path) + 'workdir; echo "DIR=$NL_TMP"; ls -ld "$NL_TMP"\n'
    path = _bin(tmp_path, BASE + ["uname"])
    r = subprocess.run(["/bin/sh", "-c", code], capture_output=True, text=True,
                       env={"PATH": path, "HOME": str(tmp_path), "TMP": str(evil), "NL_TMP": str(evil)})
    assert r.returncode == 0, r.stderr
    d = re.search(r"DIR=(.*)", r.stdout).group(1)
    assert d not in (str(evil), "/tmp", "") and "drwx------" in r.stdout
    assert not Path(d).exists()  # removed on exit


def test_a_failed_command_link_falls_back_to_the_note_under_set_e(tmp_path):
    """sudo -n refusing (a password would be needed) must not abort the script before the plain note."""
    if not os.path.isdir("/usr/local/bin"):
        pytest.skip("needs /usr/local/bin to exist")
    home = tmp_path / "home"
    (home / ".local/bin").mkdir(parents=True)
    (home / ".local/bin/nightlight").write_text("#!/bin/sh\n")
    fakes = {"uname": 'case "$1" in -s) echo Linux;; -m) echo x86_64;; esac\n', "id": "echo 1000\n",
             "sudo": "exit 1\n"}
    path = _bin(tmp_path, [t for t in BASE if t != "id"], fakes)
    link = tmp_path / "ulb" / "nightlight"
    code = "set -eu\n" + _functions(tmp_path) + f"LINK={link}\n" + 'link_command; echo "NOTE=${NOTE:-}"; echo REACHED\n'
    r = subprocess.run(["/bin/sh", "-c", code], capture_output=True, text=True,
                       env={"PATH": path + ":/usr/local/bin", "HOME": str(home)})
    assert r.returncode == 0, r.stderr
    assert "REACHED" in r.stdout and "~/.local/bin/nightlight status" in r.stdout
    assert not link.exists()
